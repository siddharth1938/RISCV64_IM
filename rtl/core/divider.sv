`timescale 1ns/1ps

module divider
    import riscv_pkg::*;
    import riscv_alu_pkg::*;
(

    //--------------------------------------------------------------------------
    // Operands
    //--------------------------------------------------------------------------

    input  xlen_t   operand_a_i,
    input  xlen_t   operand_b_i,

    //--------------------------------------------------------------------------
    // Divide Operation
    //--------------------------------------------------------------------------

    input  alu_op_t div_op_i,

    //--------------------------------------------------------------------------
    // Output
    //--------------------------------------------------------------------------

    output xlen_t   result_o

);

    //==========================================================================
    // Internal Result
    //==========================================================================

    xlen_t result;

    //==========================================================================
    // Combinational Divider
    //==========================================================================

    always_comb begin

        //--------------------------------------------------------------
        // Default
        //--------------------------------------------------------------

        result = '0;

        //--------------------------------------------------------------
        // Operation Select
        //--------------------------------------------------------------

        unique case (div_op_i)

            //----------------------------------------------------------
            // DIV (Signed)
            //----------------------------------------------------------

            ALU_DIV: begin

                if (operand_b_i == 0)
                    result = '1;

                else if (($signed(operand_a_i) == -(64'sd1 << 63)) &&
                         ($signed(operand_b_i) == -1))
                    result = operand_a_i;

                else
                    result = $signed(operand_a_i) /
                             $signed(operand_b_i);

            end

            //----------------------------------------------------------
            // DIVU (Unsigned)
            //----------------------------------------------------------

            ALU_DIVU: begin

                if (operand_b_i == 0)
                    result = '1;

                else
                    result = operand_a_i / operand_b_i;

            end

            //----------------------------------------------------------
            // REM (Signed)
            //----------------------------------------------------------

            ALU_REM: begin

                if (operand_b_i == 0)
                    result = operand_a_i;

                else if (($signed(operand_a_i) == -(64'sd1 << 63)) &&
                         ($signed(operand_b_i) == -1))
                    result = '0;

                else
                    result = $signed(operand_a_i) %
                             $signed(operand_b_i);

            end

            //----------------------------------------------------------
            // REMU (Unsigned)
            //----------------------------------------------------------

            ALU_REMU: begin

                if (operand_b_i == 0)
                    result = operand_a_i;

                else
                    result = operand_a_i % operand_b_i;

            end

            //----------------------------------------------------------
            // Default
            //----------------------------------------------------------

            default:
                result = '0;

        endcase

    end

    //==========================================================================
    // Output Logic
    //==========================================================================

    assign result_o = result;

endmodule : divider
