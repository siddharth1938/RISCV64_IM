// Description  :
//   Testbench for verifying the RV64M Divider.
//
//==============================================================================

`timescale 1ns/1ps

module tb_divider;

    import riscv_pkg::*;
    import riscv_alu_pkg::*;

    //--------------------------------------------------------------------------
    // DUT Signals
    //--------------------------------------------------------------------------

    xlen_t   operand_a_i;
    xlen_t   operand_b_i;
    alu_op_t div_op_i;

    xlen_t   result_o;

    //--------------------------------------------------------------------------
    // DUT
    //--------------------------------------------------------------------------

    divider dut (

        .operand_a_i (operand_a_i),
        .operand_b_i (operand_b_i),
        .div_op_i    (div_op_i),

        .result_o    (result_o)

    );

    //--------------------------------------------------------------------------
    // Waveform
    //--------------------------------------------------------------------------

    initial begin
        $dumpfile("../waves/tb_divider.vcd");
        $dumpvars(0, tb_divider);
    end

    //--------------------------------------------------------------------------
    // Test Sequence
    //--------------------------------------------------------------------------

    initial begin

        $display("");
        $display("========================================================");
        $display("              RV64M DIVIDER TESTBENCH");
        $display("========================================================");

        //--------------------------------------------------------------
        // DIV
        //--------------------------------------------------------------

        operand_a_i = 20;
        operand_b_i = 5;
        div_op_i    = ALU_DIV;

        #10;

        if (result_o != 4)
            $fatal(1,"DIV FAILED");

        //--------------------------------------------------------------
        // DIVU
        //--------------------------------------------------------------

        operand_a_i = 21;
        operand_b_i = 5;
        div_op_i    = ALU_DIVU;

        #10;

        if (result_o != 4)
            $fatal(1,"DIVU FAILED");

        //--------------------------------------------------------------
        // REM
        //--------------------------------------------------------------

        operand_a_i = 22;
        operand_b_i = 5;
        div_op_i    = ALU_REM;

        #10;

        if (result_o != 2)
            $fatal(1,"REM FAILED");

        //--------------------------------------------------------------
        // REMU
        //--------------------------------------------------------------

        operand_a_i = 23;
        operand_b_i = 5;
        div_op_i    = ALU_REMU;

        #10;

        if (result_o != 3)
            $fatal(1,"REMU FAILED");

        //--------------------------------------------------------------
        // DIV BY ZERO
        //--------------------------------------------------------------

        operand_a_i = 100;
        operand_b_i = 0;
        div_op_i    = ALU_DIV;

        #10;

        if (result_o != 64'hFFFFFFFFFFFFFFFF)
            $fatal(1,"DIV BY ZERO FAILED");

        //--------------------------------------------------------------
        // DIVU BY ZERO
        //--------------------------------------------------------------

        operand_a_i = 100;
        operand_b_i = 0;
        div_op_i    = ALU_DIVU;

        #10;

        if (result_o != 64'hFFFFFFFFFFFFFFFF)
            $fatal(1,"DIVU BY ZERO FAILED");

        //--------------------------------------------------------------
        // REM BY ZERO
        //--------------------------------------------------------------

        operand_a_i = 64'd1234;
        operand_b_i = 0;
        div_op_i    = ALU_REM;

        #10;

        if (result_o != 64'd1234)
            $fatal(1,"REM BY ZERO FAILED");

        //--------------------------------------------------------------
        // REMU BY ZERO
        //--------------------------------------------------------------

        operand_a_i = 64'd5678;
        operand_b_i = 0;
        div_op_i    = ALU_REMU;

        #10;

        if (result_o != 64'd5678)
            $fatal(1,"REMU BY ZERO FAILED");

        //--------------------------------------------------------------
        // DIV OVERFLOW
        // INT64_MIN / -1
        //--------------------------------------------------------------

        operand_a_i = 64'h8000000000000000;
        operand_b_i = 64'hFFFFFFFFFFFFFFFF;
        div_op_i    = ALU_DIV;

        #10;

        if (result_o != 64'h8000000000000000)
            $fatal(1,"DIV OVERFLOW FAILED");

        //--------------------------------------------------------------
        // REM OVERFLOW
        // INT64_MIN % -1
        //--------------------------------------------------------------

        operand_a_i = 64'h8000000000000000;
        operand_b_i = 64'hFFFFFFFFFFFFFFFF;
        div_op_i    = ALU_REM;

        #10;

        if (result_o != 64'd0)
            $fatal(1,"REM OVERFLOW FAILED");

        //--------------------------------------------------------------
        // PASS
        //--------------------------------------------------------------

        $display("");
        $display("========================================================");
        $display("      RV64M DIVIDER TEST PASSED SUCCESSFULLY");
        $display("========================================================");

        $finish;

    end

endmodule : tb_divider
